const STRINGS: Record<LangCode, Dict> = { es: ES, en: EN, pt: PT };

/** Translate a UI key for a language, with {var} interpolation; falls back to Spanish. */
export function t(lang: LangCode, key: string, vars?: Record<string, string | number>): string {
  let s = STRINGS[lang]?.[key] ?? ES[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
